"""Copy a built page into the website checkout's working tree.

This only writes files; it never commits or pushes, and refuses to run while a site build
looks active (the site's rule: no content edits during a build). The first publish also adds
the site scaffolding the ``cases`` collection needs: the collection in ``_config.yml``, the
``/cases/`` listing page (in the navbar, ``nav_order: 3``), the relabelling of the old listing to ``datasets``
(user, 2026-10-12: ``cases`` gets the navbar entry, ``datasets`` stays for actual datasets; ``nav_order`` must be
unique, so the old listing moves to 3.5) and the cases
bibliography ``_bibliography/cases.bib`` (separate from ``papers.bib`` so these references do
not appear on the publications page).
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

from ..spec import Page
from .bib import bibPath

__all__ = ['publishPage']

_LISTING = """---
layout: page
title: cases
permalink: /cases/
description: Documented validation and example cases of warpSPH -- origin, setup, results, solver comparison and reference comparison, each with a notebook.
nav: true
nav_order: 3
display_categories: [compressible, compressible-walls, free-surface, periodic, wall-bounded, boundaries, demos]
horizontal: false
---

<div class="projects">
  {% for category in page.display_categories %}
  {% assign categorized = site.cases | where: "category", category %}
  {% if categorized.size > 0 %}
  <a id="{{ category }}" href=".#{{ category }}">
    <h2 class="category">{{ category }}</h2>
  </a>
  {% assign sorted_projects = categorized | sort: "importance" %}
  <div class="row row-cols-1 row-cols-md-3">
    {% for project in sorted_projects %}
      {% include projects.liquid %}
    {% endfor %}
  </div>
  {% endif %}
  {% endfor %}
</div>
"""

_COLLECTION = """  cases:
    output: true
    permalink: /:collection/:title/
"""


_DATASETS_DESCRIPTION = ('Datasets, for example the training data of the learned models. The documented validation and example '
                         'cases of warpSPH are under /cases/.')


def _relabelDatasets(siteDir: Path) -> None:
    """The old listing was titled ``cases`` at ``nav_order: 3``; it becomes ``datasets`` (front matter only; the legacy
    case pages in ``_datasets/`` stay listed there until a warpSPH page replaces them)."""
    import re
    page = siteDir / '_pages' / 'datasets.md'
    if not page.exists():
        return
    text = page.read_text()
    new = re.sub(r'^title:.*$', 'title: datasets', text, count=1, flags=re.M)
    new = re.sub(r'^nav_order:.*$', 'nav_order: 3.5', new, count=1, flags=re.M)
    new = re.sub(r'^description:.*$', 'description: ' + _DATASETS_DESCRIPTION, new, count=1, flags=re.M)
    if new != text:
        page.write_text(new)
        print('  _pages/datasets.md: title -> datasets, nav_order -> 3.5, description reworded')


def _buildRunning() -> bool:
    out = subprocess.run(['pgrep', '-fa', 'jekyll'], capture_output=True, text=True).stdout
    return bool(out.strip())


def publishPage(page: Page, site: str) -> None:
    siteDir = Path(site).expanduser().resolve()
    if not (siteDir / '_config.yml').exists():
        raise FileNotFoundError(f'{siteDir} is not a Jekyll site')
    if _buildRunning():
        raise RuntimeError('a jekyll process is running; publish after the site build has finished')
    built = page.root / 'build' / 'site'
    src = built / '_cases' / f'{page.slug}.md'
    if not src.exists():
        raise FileNotFoundError(f'{src} missing; run `warpsph-cases build {page.slug}` first')

    # scaffolding (idempotent)
    config = siteDir / '_config.yml'
    text = config.read_text()
    if not any(line.strip() == 'cases:' for line in text.splitlines()):
        marker = '  datasets:\n    output: true\n    permalink: /:collection/:title/\n'
        if marker not in text:
            raise RuntimeError('could not find the datasets collection in _config.yml to extend; add `cases` by hand')
        config.write_text(text.replace(marker, marker + _COLLECTION, 1))
        print('  _config.yml: added the cases collection')
    listing = siteDir / '_pages' / 'cases.md'
    if not listing.exists():
        listing.write_text(_LISTING)
        print('  _pages/cases.md: created (navbar entry, nav_order 3)')
    _relabelDatasets(siteDir)

    # bibliography: add only the keys this page needs
    from .bib import readBib
    bibText = bibPath(page.root).read_text()
    target = siteDir / '_bibliography' / 'cases.bib'
    have = target.read_text() if target.exists() else '% References cited by the /cases/ pages (generated by warpSPHCases).\n\n'
    import re
    added = []
    body = src.read_text()
    for key in dict.fromkeys(re.findall(r'\{%\s*cite\s+(\S+)', body)):
        if f'{{{key},' not in have:
            m = re.search(r'@\w+\s*\{\s*' + re.escape(key) + r'\s*,', bibText)
            i, depth = m.end(), 1
            while depth:
                depth += {'{': 1, '}': -1}.get(bibText[i], 0)
                i += 1
            have += bibText[m.start():i] + '\n\n'
            added.append(key)
    target.parent.mkdir(exist_ok=True)
    target.write_text(have)
    if added:
        print(f'  _bibliography/cases.bib: added {", ".join(added)}')

    # the page and its assets
    (siteDir / '_cases').mkdir(exist_ok=True)
    shutil.copy2(src, siteDir / '_cases' / src.name)
    dst = siteDir / 'assets' / 'img' / 'cases' / page.slug
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(built / 'assets' / 'img' / 'cases' / page.slug, dst)
    print(f'published {page.slug} to {siteDir} (working tree only: nothing committed or pushed)')
